#[derive(Debug, Clone, PartialEq)]
enum GoType {
    /// Nothing known yet, like the items of an empty array.
    Unknown,
    Null,
    Any,
    Bool,
    /// Whole numbers from the first value to the second.
    Int(i128, i128),
    Float,
    /// Numbers mixed with numeric strings, like 1 and "2".
    Number,
    /// A string holding a number: a string on its own, json.Number next to numbers.
    NumericString,
    Str,
    Ptr(Box<GoType>),
    Slice(Box<GoType>),
    Map(Box<GoType>),
    /// `{}`: takes the shape of the other samples.
    EmptyObject,
    Struct(Vec<Field>),
}

#[derive(Debug, Clone, PartialEq)]
struct Field {
    key: String,
    ty: GoType,
    /// Missing from some samples.
    optional: bool,
}

impl Field {
    fn make_optional(self) -> Field {
        Field {
            ty: nullable(self.ty),
            optional: true,
            ..self
        }
    }
}

fn infer(value: &Value) -> GoType {
    match value {
        Value::Null => GoType::Null,
        Value::Bool(_) => GoType::Bool,
        Value::Number(n) => match (n.as_i64(), n.as_u64()) {
            (Some(i), _) => GoType::Int(i.into(), i.into()),
            (None, Some(u)) => GoType::Int(u.into(), u.into()),
            _ => GoType::Float,
        },
        Value::String(s) => {
            // encoding/json reads "12" into a json.Number, but not " 12".
            let numeric = !s.is_empty()
                && s.trim() == s
                && serde_json::from_str::<serde_json::Number>(s).is_ok();
            if numeric {
                GoType::NumericString
            } else {
                GoType::Str
            }
        }
        Value::Array(items) => GoType::Slice(Box::new(merge_all(items.iter().map(infer)))),
        Value::Object(map) if map.is_empty() => GoType::EmptyObject,
        Value::Object(map) if is_collection(map) => {
            GoType::Map(Box::new(merge_all(map.values().map(infer))))
        }
        Value::Object(map) => GoType::Struct(
            map.iter()
                .map(|(key, value)| Field {
                    key: key.clone(),
                    ty: infer(value),
                    optional: false,
                })
                .collect(),
        ),
    }
}

/// An object keyed by data rather than field names, like prices by symbol or
/// counts by date, which reads better as a map.
fn is_collection(map: &Map<String, Value>) -> bool {
    if map.len() < 2 {
        return false;
    }
    if map
        .keys()
        .all(|key| key.starts_with(|c: char| c.is_ascii_digit()))
    {
        return true;
    }
    // Objects that all have the same keys: {"BTC": {"price": 1}, "ETH": {"price": 2}}.
    let mut values = map.values();
    let first = values.next().and_then(key_set);
    first.is_some() && values.all(|value| key_set(value) == first)
}

/// A non-empty object's keys, sorted.
fn key_set(value: &Value) -> Option<Vec<&String>> {
    let object = value.as_object().filter(|o| !o.is_empty())?;
    let mut keys: Vec<&String> = object.keys().collect();
    keys.sort();
    Some(keys)
}

fn merge_all(types: impl Iterator<Item = GoType>) -> GoType {
    types.fold(GoType::Unknown, merge)
}

fn merge(a: GoType, b: GoType) -> GoType {
    use GoType::*;
    if a == b {
        return a;
    }
    match (a, b) {
        (Unknown, t) | (t, Unknown) => t,
        (Null, t) | (t, Null) => nullable(t),
        (Any, _) | (_, Any) => Any,
        (Ptr(x), y) | (y, Ptr(x)) => nullable(merge(*x, y)),
        (Int(min1, max1), Int(min2, max2)) => Int(min1.min(min2), max1.max(max2)),
        (Int(..), Float) | (Float, Int(..)) => Float,
        (Int(..) | Float | Number | NumericString, Int(..) | Float | Number | NumericString) => {
            Number
        }
        (Str, NumericString) | (NumericString, Str) => Str,
        (Slice(x), Slice(y)) => Slice(Box::new(merge(*x, *y))),
        (Map(x), Map(y)) => Map(Box::new(merge(*x, *y))),
        (EmptyObject, Map(m)) | (Map(m), EmptyObject) => Map(m),
        (EmptyObject, Struct(fields)) | (Struct(fields), EmptyObject) => {
            Struct(fields.into_iter().map(Field::make_optional).collect())
        }
        (Struct(f1), Struct(f2)) => merge_structs(f1, f2),
        (Map(m), Struct(fields)) | (Struct(fields), Map(m)) => {
            Map(Box::new(fields.into_iter().fold(*m, |t, f| merge(t, f.ty))))
        }
        _ => Any,
    }
}

/// The type once null is allowed. Slices, maps and any already allow it as nil.
fn nullable(t: GoType) -> GoType {
    match t {
        GoType::Unknown | GoType::Null | GoType::Any => GoType::Any,
        GoType::Ptr(_) | GoType::Slice(_) | GoType::Map(_) | GoType::EmptyObject => t,
        other => GoType::Ptr(Box::new(other)),
    }
}

fn merge_structs(f1: Vec<Field>, f2: Vec<Field>) -> GoType {
    let keys1: HashSet<&str> = f1.iter().map(|f| f.key.as_str()).collect();
    let shared = f2.iter().filter(|f| keys1.contains(f.key.as_str())).count();
    // Scalars under entirely different keys: a keyed collection, not a record.
    if shared == 0 && f1.iter().chain(&f2).all(|f| is_scalar(&f.ty)) {
        return GoType::Map(Box::new(merge_all(f1.into_iter().chain(f2).map(|f| f.ty))));
    }

    // A record whose fields are optional where only one side has them.
    let mut others: HashMap<String, Field> =
        f2.iter().cloned().map(|f| (f.key.clone(), f)).collect();
    let mut fields: Vec<Field> = f1
        .into_iter()
        .map(|f| match others.remove(&f.key) {
            Some(other) => Field {
                ty: merge(f.ty, other.ty),
                optional: f.optional || other.optional,
                key: f.key,
            },
            None => f.make_optional(),
        })
        .collect();
    fields.extend(
        f2.into_iter()
            .filter(|f| others.contains_key(&f.key))
            .map(Field::make_optional),
    );
    GoType::Struct(fields)
}

/// Anything but a struct, map or slice, possibly behind a pointer.
fn is_scalar(t: &GoType) -> bool {
    match t {
        GoType::Ptr(inner) => is_scalar(inner),
        GoType::Struct(_) | GoType::Map(_) | GoType::Slice(_) | GoType::EmptyObject => false,
        _ => true,
    }
}

