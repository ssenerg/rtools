//! Generates Go types from sample JSON, ready for encoding/json and formatted
//! the way gofmt formats them.

use crate::{json, utils};
use clap::Parser;
use serde_json::{Map, Value};
use std::collections::{HashMap, HashSet};
use std::io::{self, IsTerminal};
use std::process::exit;

#[derive(Parser, Debug)]
#[command(after_help = "\
Examples:
  curl -s https://api.example.com/users | rtools gostruct -n Users
  rtools gostruct response.json --no-tags

The objects in an array merge into one struct. Fields missing from some of them get a
pointer and omitempty; fields that are sometimes null get a pointer.")]
pub struct Args {
    /// JSON file. If omitted, reads from stdin (pipe)
    file: Option<String>,

    /// JSON file, the same as FILE
    #[arg(short, long, value_name = "FILE", conflicts_with = "file", hide = true)]
    input: Option<String>,

    /// Name of the Go type
    #[arg(short, long, default_value = "AutoGenerated")]
    name: String,

    /// Leave out json tags where the field name already matches the key
    #[arg(long)]
    no_tags: bool,

    /// Add json tags: the default, kept so existing commands keep working
    #[arg(short, long, hide = true, conflicts_with = "no_tags")]
    json: bool,
}

pub fn run(args: &Args, copy: bool) {
    if let Err(e) = generate_code(args).and_then(|code| utils::emit(&code, copy)) {
        eprintln!("Error: {e}");
        exit(1);
    }
}

fn generate_code(args: &Args) -> Result<String, String> {
    let file = args.file.clone().or_else(|| args.input.clone());
    if file.is_none() && io::stdin().is_terminal() {
        return Err("no JSON given: pass a file or pipe it in".to_string());
    }
    check_type_name(&args.name)?;
    let value = json::parse(&utils::read_stdin_or_file(&file)?)?;
    let generated = generate(&value, &args.name, !args.no_tags);
    for key in &generated.skipped {
        eprintln!(
            "Warning: skipped the key {key:?}: encoding/json can't match it to a struct field"
        );
    }
    Ok(generated.code)
}

struct Generated {
    code: String,
    /// Keys no struct field can decode, like ones with a comma.
    skipped: Vec<String>,
}

fn generate(value: &Value, name: &str, tags: bool) -> Generated {
    let mut renderer = Renderer {
        tags,
        skipped: Vec::new(),
    };
    let body = renderer.render(&infer(value), 0);
    Generated {
        code: format!("type {name} {body}"),
        skipped: renderer.skipped,
    }
}

const GO_KEYWORDS: [&str; 25] = [
    "break",
    "case",
    "chan",
    "const",
    "continue",
    "default",
    "defer",
    "else",
    "fallthrough",
    "for",
    "func",
    "go",
    "goto",
    "if",
    "import",
    "interface",
    "map",
    "package",
    "range",
    "return",
    "select",
    "struct",
    "switch",
    "type",
    "var",
];

fn check_type_name(name: &str) -> Result<(), String> {
    let valid = name
        .chars()
        .next()
        .is_some_and(|c| c.is_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_alphanumeric() || c == '_')
        && !GO_KEYWORDS.contains(&name);
    if valid {
        Ok(())
    } else {
        Err(format!(
            "{name:?} isn't a valid Go type name. Try {}",
            field_name(name)
        ))
    }
}

